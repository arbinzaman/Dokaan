// All timestamps are computed relative to the current date so charts, filters,
// and "today / this month" analytics always show fresh, meaningful data.

const daysAgo = (days, hour = 11, minute = 30) => {
  const d = new Date();
  d.setDate(d.getDate() - days);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
};

const monthsAgo = (months, dayOfMonth = 14) => {
  const d = new Date();
  d.setDate(1);
  d.setMonth(d.getMonth() - months);
  const maxDay = new Date(d.getFullYear(), d.getMonth() + 1, 0).getDate();
  d.setDate(Math.min(dayOfMonth, maxDay));
  d.setHours(14, 15, 0, 0);
  return d.toISOString();
};

